pub fn federal_district(region: &str) -> &'static str {
    let r = normalize(region);
    if contains_any(
        &r,
        &[
            "москва",
            "московская область",
            "белгород",
            "брянск",
            "владимир",
            "воронеж",
            "иванов",
            "калуга",
            "костром",
            "курск",
            "липец",
            "орлов",
            "рязань",
            "смоленск",
            "тамбов",
            "твер",
            "тула",
            "ярослав",
        ],
    ) {
        "Центральный"
    } else if contains_any(
        &r,
        &[
            "санкт-петербург",
            "ленинград",
            "карел",
            "коми",
            "архангель",
            "волог",
            "калининград",
            "мурман",
            "новгород",
            "псков",
            "ненецк",
        ],
    ) {
        "Северо-Западный"
    } else if contains_any(
        &r,
        &[
            "адыге",
            "калмык",
            "крым",
            "краснодар",
            "астрахан",
            "волгоград",
            "ростов",
            "севастопол",
            "донецк",
            "луганск",
            "запорож",
            "херсон",
        ],
    ) {
        "Южный"
    } else if contains_any(
        &r,
        &[
            "дагестан",
            "ингуш",
            "кабардино",
            "карачаево",
            "северная осет",
            "чечен",
            "ставропол",
        ],
    ) {
        "Северо-Кавказский"
    } else if contains_any(
        &r,
        &[
            "башкортостан",
            "марий эл",
            "мордов",
            "татарстан",
            "удмурт",
            "чуваш",
            "перм",
            "киров",
            "нижегород",
            "оренбург",
            "пенз",
            "самар",
            "саратов",
            "ульянов",
        ],
    ) {
        "Приволжский"
    } else if contains_any(
        &r,
        &[
            "курган",
            "свердлов",
            "тюмен",
            "челябин",
            "ханты-мансий",
            "ямало-ненец",
        ],
    ) {
        "Уральский"
    } else if contains_any(
        &r,
        &[
            "алтай",
            "тыва",
            "хакас",
            "алтайский край",
            "краснояр",
            "иркут",
            "кемеров",
            "новосибир",
            "омск",
            "томск",
        ],
    ) {
        "Сибирский"
    } else if contains_any(
        &r,
        &[
            "бурят",
            "саха",
            "забайкал",
            "камчат",
            "примор",
            "хабаров",
            "амур",
            "магадан",
            "сахалин",
            "еврейск",
            "чукот",
        ],
    ) {
        "Дальневосточный"
    } else {
        "Специальные и зарубежные"
    }
}

fn normalize(value: &str) -> String {
    value.to_lowercase().replace('ё', "е")
}

fn contains_any(value: &str, needles: &[&str]) -> bool {
    needles.iter().any(|needle| value.contains(needle))
}

#[cfg(test)]
mod tests {
    use super::federal_district;

    #[test]
    fn maps_representative_regions() {
        assert_eq!(federal_district("город Москва"), "Центральный");
        assert_eq!(federal_district("Республика Бурятия"), "Дальневосточный");
        assert_eq!(federal_district("Пермский край"), "Приволжский");
        assert_eq!(
            federal_district("Зарубежная территория"),
            "Специальные и зарубежные"
        );
    }
}
